"""Synthetic learner-response fixtures for the scorer determinism experiment.

Constructed by hand, never generated by the API: the point of Experiment 2 is that it needs no
network, so anything nondeterministic here would be our own fault rather than the model's.

Responses are stored as plain dicts with string trait keys -- the same shape the scorer receives
when a class's responses are loaded from data/responses/*.json -- so pydantic coercion and its
validators are exercised, not bypassed. Fixtures expected to RAISE are included deliberately:
the scorer's error path is part of its contract (empty response sets, all-zero allocations,
duplicate items, budget mismatches), and an error message that changes between runs is just as
much a determinism failure as a profile that changes.

Rwanda locale settings the numbers are built against: point_budget=10, items_per_assessment=10.
"""
from __future__ import annotations

from typing import Any, Dict, List

BUDGET = 10
MAX_ITEMS = 10


def _r(item_id: str, visual: int, game: int, structured: int, story: int) -> Dict[str, Any]:
    return {
        "item_id": item_id,
        "allocations": {
            "visual": visual,
            "game": game,
            "structured": structured,
            "story": story,
        },
    }


def _repeat(prefix: str, alloc: tuple, count: int, start: int = 1) -> List[Dict[str, Any]]:
    return [_r(f"{prefix}-{i:02d}", *alloc) for i in range(start, start + count)]


def _seq(prefix: str, allocs: List[tuple]) -> List[Dict[str, Any]]:
    return [_r(f"{prefix}-{i:02d}", *a) for i, a in enumerate(allocs, start=1)]


